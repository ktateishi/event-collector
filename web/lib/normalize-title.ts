/**
 * タイトルの表記ゆれを吸収して重複判定に使うための正規化。
 *
 * 収集元サイトによって、同じイベントでも「『』の有無」「括弧の種類」
 * 「全角/半角スペース」などの表記が微妙に異なることが実運用で確認されている
 * （例:「ホラー・メイズ「バイオハザード レクイエム」ザ・ダイブ」と
 * 「ホラー・メイズ「『バイオハザード レクイエム』ザ・ダイブ」」）。
 * これらは意味的に完全に同じイベントなので、括弧類・区切り記号・空白をすべて
 * 除去してから比較する。
 *
 * 除去しすぎて別イベントを誤って同一視するリスクを避けるため、装飾記号のみを
 * 対象とし、本文の文字（かな・漢字・英数字）は一切変更しない。
 */
export function normalizeTitle(title: string): string {
  return title
    .toLowerCase()
    .replace(/[「」『』()（）\[\]［］【】〈〉《》・、,]/g, "")
    .replace(/\s+/g, "")
    .trim();
}
